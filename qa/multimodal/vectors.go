// DefaultBase is the production gateway. HANZO_API_URL may name the URL with or without the /v1
// suffix (the docs print it without). These env names are shared with qa/crossmodel (#138) on
// purpose — one CI secret configures both suites, and README.md prints them once per suite.
const DefaultBase = "https://api.hanzo.ai"

const (
	BaseURLEnv    = "HANZO_API_URL"
	KeyEnv        = "HANZO_API_KEY"   // keyed red-team lane; absent → the matrix skips
	ReportEnv     = "HANZO_QA_REPORT" // artifact path for report.json (+ a .md twin beside it)
	LivePublicEnv = "HANZO_QA_LIVE"   // opts the key-free public checks into real network calls

	// RequestTimeout bounds one model round trip per #138's precedent; reasoning rows can be
	// slow to first token, so it is generous — every cell still fails fast on its own context.
	RequestTimeout = 180 * time.Second
)

// BaseURL resolves the gateway root, ending in /v1 (the same shape qa/crossmodel prints).
func BaseURL() string {
	base := strings.TrimRight(os.Getenv(BaseURLEnv), "/")
	if base == "" {
		base = DefaultBase
	}
	if !strings.HasSuffix(base, "/v1") {
		base += "/v1"
	}
	return base
}
